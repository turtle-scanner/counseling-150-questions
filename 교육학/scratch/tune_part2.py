rubric[100] = (
    "1. 만성적 분노와 주 3회 이상의 심각한 언어·행동 분노 폭발이다.\n"
    "2. 분노 발작 사이에도 지속적으로 과민한 기분을 유지한다.\n"
    "3. [임상 개입] 분노 촉발 자극을 조절하고 이완 기법을 훈련한다.\n"
    "4. [치료 의의] 감정 조절력을 길러주고 품행장애로의 악화를 막는다."
)

lines_seen = set()
errors = []
for n, ans in rubric.items():
    ls = [l.strip() for l in ans.split('\n') if l.strip()]
    if len(ls) != 4:
        errors.append(f"Item {n} has {len(ls)} lines")
    for idx, l in enumerate(ls):
        if len(l) < 30 or len(l) > 42:
            errors.append(f"Item {n} line {idx+1} ({len(l)} chars): {l}")
        if l in lines_seen:
            errors.append(f"Item {n} line {idx+1} DUPLICATE: {l}")
        lines_seen.add(l)
        if "*" in l:
            errors.append(f"Item {n} line {idx+1} Asterisk: {l}")

if errors:
    print(f"Errors found in Part 2 ({len(errors)}):")
    for e in errors:
        print(" ", e)
else:
    print("SUCCESS: Part 2 (51~100) has ZERO errors! All 200 lines strictly 30~42 chars, zero duplicates, zero asterisks!")
    with open('scratch/rubric_part2.py', 'w', encoding='utf-8') as f:
        f.write("# -*- coding: utf-8 -*-\nRUBRIC_PART2 = " + repr(rubric) + "\n")
    print("Saved scratch/rubric_part2.py successfully.")
