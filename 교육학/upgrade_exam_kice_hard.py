for (sec, num), data in UPGRADES.items():
    # find the specific block in EXAM_A or EXAM_B
    sec_pat = rf'(const {sec} = \[)(.*?)(\n\];)'
    sec_m = re.search(sec_pat, html, re.S)
    sec_body = sec_m.group(2)

    q_pat = rf'(\{{\s*num:\s*{num},\s*type:.*?passage:\s*`)(.*?)(`,\s*asks:\s*\[)(.*?)(\],\s*ans:)'
    def repl(m):
        new_p = data.get('passage', m.group(2))
        if 'asks' in data:
            new_asks = '\n      ' + ',\n      '.join("'" + a.replace("'", "\\'") + "'" for a in data['asks']) + '\n    '
        else:
            new_asks = m.group(4)
        return m.group(1) + new_p + m.group(3) + new_asks + m.group(5)

    new_sec_body, cnt = re.subn(q_pat, repl, sec_body, count=1, flags=re.S)
    assert cnt == 1, f'Failed to replace {sec} Q{num}'
    html = html[:sec_m.start(2)] + new_sec_body + html[sec_m.end(2):]

open(path, 'w', encoding='utf-8').write(html)

